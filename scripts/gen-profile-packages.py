#!/usr/bin/env python3
"""Generate the heiss-profile-* metapackages from profiles/*.toml (stdlib only).

  gen-profile-packages.py           write packages/heiss-profile-<id>/ (PKGBUILD + manifest copy)
  gen-profile-packages.py --check   exit 1 if the committed files differ from regeneration

TOML manifest -> PKGBUILD (single source of truth). Each package is EMPTY: it only
depends on the packages of its manifest and on the metapackage of every manifest it
requires. All manifests are shipped by heiss-core, so every profile is known to the
engine before its metapackage is installed. Services, drop-ins and KDE settings are
applied by the Heiss engine, not by the package.
"""
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "core"))
from heiss_core import manifest as mf  # noqa: E402

PROFILES = ("essentials", "base", "cyber", "developer")  # custom and add-ons are applied by the engine only
PKG_ROOT = os.path.join(ROOT, "packages")
HEADER = "# generated by scripts/gen-profile-packages.py from profiles/%s.toml, do not edit\n"


def pkg_name(mid):
    return "heiss-profile-" + mid


def render(m, pkgver, pkgrel):
    deps = [pkg_name(r) for r in m.requires] + list(m.packages)
    depends = "\n".join("  '%s'" % d for d in deps)
    desc = m.description["en"].replace("'", "").split(". ")[0].rstrip(".")
    return (HEADER % m.id) + """# Maintainer: Heiss OS <https://github.com/heiss-os>
pkgname=%(name)s
pkgver=%(ver)s
pkgrel=%(rel)d
pkgdesc='Heiss OS profile %(title)s: %(desc)s'
arch=('any')
url='https://github.com/heiss-os/heiss-iso'
license=('GPL-3.0-or-later')
depends=(
%(depends)s
)

package() {
  :   # metapackage: dependencies only; manifests are shipped by heiss-core
}
""" % {"name": pkg_name(m.id), "ver": pkgver, "rel": pkgrel, "title": m.name["en"], "desc": desc,
       "depends": depends}


def outputs():
    manifests = mf.load_dir(os.path.join(ROOT, "profiles"))
    with open(os.path.join(PKG_ROOT, "pkgrel.json"), encoding="utf-8") as f:
        rel = json.load(f)
    files = {}
    for mid in PROFILES:
        m = manifests[mid]
        name = pkg_name(mid)
        files[os.path.join(name, "PKGBUILD")] = render(m, rel["pkgver"], rel[name]).encode()
    return files


def main(argv):
    files = outputs()
    if "--check" in argv:
        bad = []
        for rel, data in sorted(files.items()):
            path = os.path.join(PKG_ROOT, rel)
            if not os.path.exists(path) or open(path, "rb").read() != data:
                bad.append(rel)
        if bad:
            print("generated package files out of date, run scripts/gen-profile-packages.py:", *bad, sep="\n  ")
            return 1
        print("generated package files up to date (%d)" % len(files))
        return 0
    for rel, data in sorted(files.items()):
        path = os.path.join(PKG_ROOT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        print("wrote", os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
