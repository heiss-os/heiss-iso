def render_gtk(tokens, theme, gtk4):
    p = palette(tokens, theme)
    names = [
        ("window_bg_color", p["window"]), ("window_fg_color", p["text"]),
        ("view_bg_color", p["view"]), ("view_fg_color", p["text"]),
        ("headerbar_bg_color", p["panel"]), ("headerbar_fg_color", p["text"]),
        ("headerbar_border_color", p["border"]),
        ("card_bg_color", p["window_alt"]), ("card_fg_color", p["text"]),
        ("popover_bg_color", p["panel"]), ("popover_fg_color", p["text"]),
        ("sidebar_bg_color", p["panel"]), ("sidebar_fg_color", p["text"]),
        ("accent_bg_color", p["accent"]), ("accent_fg_color", p["on_accent"]),
        ("accent_color", p["accent"]),
        ("destructive_bg_color", p["negative"]), ("destructive_fg_color", p["on_accent"]),
        ("destructive_color", p["negative"]),
        ("success_bg_color", p["positive"]), ("success_fg_color", p["on_accent"]),
        ("success_color", p["positive"]),
        ("warning_bg_color", p["neutral"]), ("warning_fg_color", p["on_accent"]),
        ("warning_color", p["neutral"]),
        ("error_bg_color", p["negative"]), ("error_fg_color", p["on_accent"]),
        ("error_color", p["negative"]),
    ]
    if not gtk4:
        names += [
            ("theme_bg_color", p["window"]), ("theme_fg_color", p["text"]),
            ("theme_base_color", p["view"]), ("theme_text_color", p["text"]),
            ("theme_selected_bg_color", p["selection"]),
            ("theme_selected_fg_color", p["on_accent"]),
            ("insensitive_fg_color", p["disabled_text"]),
            ("borders", p["border"]),
        ]
    out = ["/* " + HEADER + " */"]
    out += ["@define-color %s %s;" % (n, c.lower()) for n, c in names]
    return "\n".join(out) + "\n"


# ---------- terminals ----------

def render_kitty(tokens, theme):
    t, p = terminal(tokens, theme), palette(tokens, theme)
    out = ["# " + HEADER,
           "foreground %s" % t["fg"].lower(), "background %s" % t["bg"].lower(),
           "selection_foreground %s" % t["selection_fg"].lower(),
           "selection_background %s" % t["selection_bg"].lower(),
           "cursor %s" % t["cursor"].lower(), "cursor_text_color %s" % t["bg"].lower(),
           "url_color %s" % p["accent"].lower(),
           "active_border_color %s" % p["accent"].lower(),
           "inactive_border_color %s" % p["border"].lower()]
    out += ["color%d %s" % (i, c.lower()) for i, c in enumerate(t["ansi"])]
    return "\n".join(out) + "\n"


def render_konsole(tokens, theme):
    t = terminal(tokens, theme)
    name = tokens["themes"][theme]["name"]
    out = ["# " + HEADER,
           "[Background]", "Color=" + rgb_csv(t["bg"]), "",
           "[BackgroundIntense]", "Color=" + rgb_csv(t["bg"]), "",
           "[Foreground]", "Color=" + rgb_csv(t["fg"]), "",
           "[ForegroundIntense]", "Color=" + rgb_csv(t["fg"]), ""]
    for i, c in enumerate(t["ansi"]):
        sec = "Color%d" % i if i < 8 else "Color%dIntense" % (i - 8)
        out += ["[%s]" % sec, "Color=" + rgb_csv(c), ""]
    out += ["[General]", "Description=%s" % name, "Opacity=1", ""]
    return "\n".join(out)


# ---------- contrast pairs ----------

def text_pairs(tokens, theme):
    """(label, fg, bg, minimum) for every text/background pair we assert."""
    p = palette(tokens, theme)
    pairs = []
    for bg in ("window", "view", "panel", "button"):
        pairs.append(("text on %s" % bg, p["text"], p[bg], 4.5))
        pairs.append(("text_secondary on %s" % bg, p["text_secondary"], p[bg], 4.5))
        pairs.append(("accent on %s" % bg, p["accent"], p[bg], 4.5))
    pairs.append(("on_accent on accent", p["on_accent"], p["accent"], 4.5))
    for sem in ("negative", "neutral", "positive", "info"):
        pairs.append(("%s on window" % sem, p[sem], p["window"], 4.5))
    t = terminal(tokens, theme)
    for i, c in enumerate(t["ansi"]):
        pairs.append(("terminal color%d on terminal bg" % i, c, t["bg"], 3.0 if i in (0, 8) else 4.5))
    pairs.append(("terminal fg on terminal bg", t["fg"], t["bg"], 4.5))
    pairs.append(("terminal selection_fg on selection_bg", t["selection_fg"], t["selection_bg"], 4.5))
    return pairs
