TOKENS_PATH = os.path.join(ROOT, "branding", "tokens", "heiss-tokens.json")
THEMES = ("dark", "light")
HEADER = "generated by scripts/gen-theme.py from branding/tokens/heiss-tokens.json, do not edit"


def load(path=TOKENS_PATH):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


# ---------- color math ----------

def hex_to_rgb(h):
    h = h.lstrip("#")
    if len(h) != 6:
        raise ValueError("bad hex color: %r" % h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb_to_hex(rgb):
    return "#%02X%02X%02X" % tuple(rgb)


def mix(a, b, p):
    """Per-channel a*(1-p)+b*p, round half up. a, b are #RRGGBB strings."""
    ra, rb = hex_to_rgb(a), hex_to_rgb(b)
    out = []
    for x, y in zip(ra, rb):
        v = x * (1 - p) + y * p
        out.append(int(v + 0.5))
    return rgb_to_hex(out)


def luminance(h):
    def lin(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in hex_to_rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def rgb_csv(h):
    return "%d,%d,%d" % hex_to_rgb(h)


# ---------- resolved palette ----------

def palette(tokens, theme):
    """Base + added + derived colors for a theme, as {name: '#RRGGBB'}."""
    t = tokens["themes"][theme]
    p = dict(t["base"])
    p.update(t["added"])
    p["hover"] = mix(p["button"], p["text"], 0.08)
    p["pressed"] = mix(p["button"], p["text"], 0.14)
    p["border"] = mix(p["window"], p["text"], 0.14)
    p["disabled_text"] = mix(p["text"], p["window"], 0.55)
    p["focus_ring"] = p["accent"]
    p["selection"] = p["accent"]
    return p


def terminal(tokens, theme):
    t = tokens["themes"][theme]["terminal"]
    p = palette(tokens, theme)
    return {
        "bg": p[t["bg"]], "fg": p[t["fg"]], "cursor": p[t["cursor"]],
        "selection_bg": p[t["selection_bg"]], "selection_fg": p[t["selection_fg"]],
        "ansi": list(t["ansi"]),
    }


